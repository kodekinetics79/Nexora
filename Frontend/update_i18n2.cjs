let content = fs.readFileSync('src/i18n.ts', 'utf8');

for (const [lang, translations] of Object.entries(missingKeys)) {
  const newTranslationsStr = Object.entries(translations)
    .map(([k, v]) => `,\n      "${k}": "${v.replace(/"/g, '\\"')}"`)
    .join('');

  // Find where the translation block for this language ends
  // We look for "process_lead_to_rfq" which is the last item we added
  const regex = new RegExp(`(${lang}:\\s*\\{\\s*translation:\\s*\\{[\\s\\S]*?"process_lead_to_rfq"\\s*:\\s*"[^"]+")(\\s*\\})`, 'g');
  
  if (regex.test(content)) {
    content = content.replace(regex, `$1${newTranslationsStr}$2`);
    console.log(`Added missing keys for ${lang}`);
  } else {
    console.log(`Failed to find translation block for ${lang}`);
  }
}

fs.writeFileSync('src/i18n.ts', content, 'utf8');
console.log('i18n.ts updated successfully.');
